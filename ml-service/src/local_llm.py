"""
local_llm.py
------------
Local LLM communication service for FinSight AI.
Connects the deterministic Explanation Engine to a local OpenAI-compatible
inference server (such as LM Studio, Ollama, vLLM, or LocalAI).

Responsibilities:
- Send compact structured analysis to local LLM.
- Enforce strict system prompt preventing financial advice or hallucinated data.
- Enforce structured JSON output format.
- Handle timeout, server offline/unreachable, malformed output gracefully.
- Fall back seamlessly to deterministic output without throwing errors.
- Never transmit raw OHLCV candle histories (token-efficient).
"""

import json
import logging
import os
import re
from pathlib import Path
import urllib.request
import urllib.error
from typing import Any, Dict, List, Optional, Tuple

# Try loading .env from ml-service or workspace root
try:
    from dotenv import load_dotenv
    _env_candidates = [
        Path.cwd() / ".env",
        Path(__file__).resolve().parent.parent / ".env",
        Path(__file__).resolve().parent.parent.parent / ".env",
    ]
    for _p in _env_candidates:
        if _p.is_file():
            load_dotenv(_p, override=False)
except ImportError:
    pass

logger = logging.getLogger("finsight-llm")

# -----------------------------------------------------------------------------
# Configuration from environment
# -----------------------------------------------------------------------------
def is_llm_enabled() -> bool:
    val = os.getenv("LLM_ENABLED", "false").strip().lower()
    return val in ("true", "1", "yes", "on")


def get_llm_base_url() -> str:
    url = os.getenv("LLM_BASE_URL", "http://localhost:1234/v1").strip()
    return url.rstrip("/")


def get_llm_api_key() -> str:
    return os.getenv("LLM_API_KEY", "lm-studio").strip()


def get_configured_model() -> str:
    return os.getenv("LLM_MODEL", "").strip()


def get_llm_timeout() -> float:
    try:
        return float(os.getenv("LLM_TIMEOUT_SECONDS", "15"))
    except ValueError:
        return 15.0


def get_llm_temperature() -> float:
    try:
        return float(os.getenv("LLM_TEMPERATURE", "0.2"))
    except ValueError:
        return 0.2


def get_llm_max_tokens() -> int:
    try:
        return int(os.getenv("LLM_MAX_TOKENS", "600"))
    except ValueError:
        return 600


# -----------------------------------------------------------------------------
# Model auto-discovery
# -----------------------------------------------------------------------------
_cached_active_model: Optional[str] = None


def discover_local_model(base_url: str, api_key: str, timeout: float = 3.0) -> Optional[str]:
    """
    Probes the local OpenAI-compatible server at {base_url}/models to discover
    the active/loaded model name if LLM_MODEL is not explicitly configured.
    """
    global _cached_active_model
    configured = get_configured_model()
    if configured:
        return configured

    if _cached_active_model:
        return _cached_active_model

    models_endpoint = f"{base_url}/models"
    req = urllib.request.Request(
        models_endpoint,
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "User-Agent": "FinSight-AI/2.0",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            if resp.status == 200:
                payload = json.loads(resp.read().decode("utf-8"))
                data = payload.get("data", [])
                if data and isinstance(data, list):
                    # Filter out embedding models if possible
                    gen_models = [
                        m["id"]
                        for m in data
                        if "id" in m and "embed" not in m["id"].lower()
                    ]
                    chosen = gen_models[0] if gen_models else data[0].get("id")
                    _cached_active_model = chosen
                    return chosen
    except Exception as exc:
        logger.debug(f"Local LLM model discovery failed on {models_endpoint}: {exc}")

    return None


# -----------------------------------------------------------------------------
# Strict System Prompt
# -----------------------------------------------------------------------------
SYSTEM_PROMPT = """You are FinSight AI's explanation assistant.

Your job is ONLY to explain structured outputs generated by FinSight's quantitative models.

The quantitative models are authoritative for:
- trend prediction
- prediction confidence
- risk score
- risk category
- feature importance
- technical indicator values

You must NOT change, reinterpret, or contradict these values.
You must NOT invent data.
You must NOT provide personalized financial advice.
You must NOT tell the user to buy, sell, or hold a security.
You must NOT claim certainty about future prices or returns.

Explain the supplied model output clearly in simple language.
Use phrases such as:
'The model identifies...'
'The indicators show...'
'The main factors contributing to this output are...'
'This suggests...'

Clearly distinguish model output from uncertainty.
Return ONLY valid JSON matching this exact structure:
{
  "headline": "Brief 1-sentence headline capturing the model outlook and risk",
  "summary": "Clear executive summary integrating trend prediction, confidence, and primary drivers",
  "drivers": [
    {
      "feature": "Exact feature name from input",
      "explanation": "Human-readable explanation of why this feature influenced the model"
    }
  ],
  "risk_summary": "Contextualized explanation of quantitative risk score, level, and drawdowns",
  "watch_items": [
    "Item to watch 1",
    "Item to watch 2"
  ]
}"""


def _extract_json(text: str) -> Optional[Dict[str, Any]]:
    """Robustly extracts JSON from an LLM response string."""
    if not text:
        return None
    text = text.strip()

    # 1. Try direct JSON parsing
    try:
        data = json.loads(text)
        if isinstance(data, dict):
            return data
    except Exception:
        pass

    # 2. Extract from markdown ```json ... ``` or ``` ... ```
    match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    if match:
        try:
            data = json.loads(match.group(1))
            if isinstance(data, dict):
                return data
        except Exception:
            pass

    # 3. Search for outermost { and }
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1 and end > start:
        try:
            data = json.loads(text[start : end + 1])
            if isinstance(data, dict):
                return data
        except Exception:
            pass
    return None


# -----------------------------------------------------------------------------
# Main Polishing Function
# -----------------------------------------------------------------------------
def polish_explanation_with_local_llm(
    deterministic_result: Dict[str, Any],
    compact_analysis: Dict[str, Any],
) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    """
    Sends the compact analysis and deterministic baseline to the local LLM.
    Returns:
        (polished_result, llm_meta)
    
    If LLM is disabled, offline, times out, or returns invalid data, returns
    (deterministic_result, llm_meta) with llm_used=False.
    """
    enabled = is_llm_enabled()
    base_url = get_llm_base_url()
    api_key = get_llm_api_key()
    timeout = get_llm_timeout()

    llm_meta: Dict[str, Any] = {
        "enabled": enabled,
        "used": False,
        "model": None,
    }

    if not enabled:
        return deterministic_result, llm_meta

    model_name = discover_local_model(base_url, api_key, timeout=min(3.0, timeout))
    if not model_name:
        llm_meta["fallback_reason"] = "Could not discover active local model"
        logger.info("Local LLM enabled, but no local model discovered. Using deterministic fallback.")
        return deterministic_result, llm_meta

    llm_meta["model"] = model_name

    # Build token-efficient user prompt payload
    user_payload = {
        "ticker": compact_analysis.get("ticker"),
        "market": compact_analysis.get("market"),
        "prediction": compact_analysis.get("prediction"),
        "confidence": compact_analysis.get("confidence"),
        "risk_score": compact_analysis.get("risk_score"),
        "risk_category": compact_analysis.get("risk_category"),
        "key_drivers": [
            {
                "feature": d["feature"],
                "name": d["name"],
                "value": d["value"],
                "importance": d["importance"],
                "baseline_explanation": d["explanation"],
            }
            for d in deterministic_result.get("key_drivers", [])
        ],
        "indicators": {
            k: v
            for k, v in compact_analysis.get("indicators", {}).items()
            if v is not None
        },
        "risk_metrics": compact_analysis.get("risk_metrics", {}),
        "baseline_summary": deterministic_result.get("summary"),
        "baseline_trend_explanation": deterministic_result.get("trend_explanation"),
        "baseline_risk_explanation": deterministic_result.get("risk_explanation"),
        "baseline_watch_items": deterministic_result.get("watch_items", []),
    }

    prompt_content = (
        "Please polish the following quantitative model analysis into clear, natural explanations. "
        "Strictly adhere to the output JSON schema and do not alter or contradict numerical outputs:\n\n"
        f"{json.dumps(user_payload, indent=2)}"
    )

    request_body = {
        "model": model_name,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt_content},
        ],
        "temperature": get_llm_temperature(),
        "max_tokens": get_llm_max_tokens(),
    }

    chat_endpoint = f"{base_url}/chat/completions"
    req = urllib.request.Request(
        chat_endpoint,
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "User-Agent": "FinSight-AI/2.0",
        },
        data=json.dumps(request_body).encode("utf-8"),
    )

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            if resp.status != 200:
                llm_meta["fallback_reason"] = f"HTTP {resp.status} from local LLM"
                return deterministic_result, llm_meta

            resp_json = json.loads(resp.read().decode("utf-8"))
            choices = resp_json.get("choices", [])
            if not choices:
                llm_meta["fallback_reason"] = "Empty choices from local LLM"
                return deterministic_result, llm_meta

            raw_text = choices[0].get("message", {}).get("content", "")
            parsed = _extract_json(raw_text)
            if not parsed or not isinstance(parsed, dict):
                llm_meta["fallback_reason"] = "LLM output could not be parsed as JSON"
                logger.warning(f"Local LLM returned non-JSON response: {raw_text[:120]}")
                return deterministic_result, llm_meta

            # Validate and merge LLM outputs without touching authoritative quantitative values
            polished = dict(deterministic_result)

            if parsed.get("summary") and isinstance(parsed["summary"], str):
                polished["summary"] = parsed["summary"].strip()

            if parsed.get("headline") and isinstance(parsed["headline"], str):
                polished["headline"] = parsed["headline"].strip()

            if parsed.get("risk_summary") and isinstance(parsed["risk_summary"], str):
                polished["risk_explanation"] = parsed["risk_summary"].strip()

            if parsed.get("watch_items") and isinstance(parsed["watch_items"], list):
                valid_items = [str(item).strip() for item in parsed["watch_items"] if str(item).strip()]
                if valid_items:
                    polished["watch_items"] = valid_items

            # Update driver explanations if returned
            llm_drivers = parsed.get("drivers", [])
            if isinstance(llm_drivers, list) and llm_drivers:
                driver_map = {
                    d.get("feature"): d.get("explanation")
                    for d in llm_drivers
                    if isinstance(d, dict) and d.get("feature") and d.get("explanation")
                }
                for d in polished.get("key_drivers", []):
                    feat = d.get("feature")
                    if feat in driver_map:
                        d["explanation"] = driver_map[feat].strip()

            llm_meta["used"] = True
            logger.info(f"Successfully polished explanation with local LLM: {model_name}")
            return polished, llm_meta

    except (urllib.error.URLError, TimeoutError) as exc:
        llm_meta["fallback_reason"] = f"Local LLM connection error: {exc}"
        logger.info(f"Local LLM unreachable or timed out ({exc}). Using deterministic fallback.")
        return deterministic_result, llm_meta
    except Exception as exc:
        llm_meta["fallback_reason"] = f"Unexpected LLM error: {exc}"
        logger.warning(f"Error calling local LLM: {exc}. Using deterministic fallback.")
        return deterministic_result, llm_meta
